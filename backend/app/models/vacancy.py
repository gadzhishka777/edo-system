# Префикс, по которому определяется учительская должность
TEACHER_POSITION_PREFIX = "учитель"

# Максимальная учебная нагрузка (часов в неделю)
MAX_TEACHING_LOAD = 35


def is_teacher_position(position: str | None) -> bool:
    """Учительская должность? Для неё обязательна учебная нагрузка.

    Считаем учительскими все должности, начинающиеся со слова «Учитель»
    (Учитель, Учитель физики, Учитель начальных классов и т.д.).
    """
    if not position:
        return False
    return position.strip().lower().startswith(TEACHER_POSITION_PREFIX)


class Vacancy(Base):
    __tablename__ = "vacancies"

    id = Column(Integer, primary_key=True, index=True)
    uuid = Column(String(36), unique=True, index=True, nullable=False)

    # Организация-владелец вакансии
    org_id = Column(Integer, ForeignKey("organizations.id"), nullable=False, index=True)

    # Наименование вакансии
    name = Column(String(500), nullable=False)

    # Должность по классификатору
    position = Column(String(500), nullable=False)

    # Учебная нагрузка, часов в неделю (только для учительских должностей, не более 35)
    teaching_load = Column(Integer, nullable=True)

    # Описание вакансии
    description = Column(Text, nullable=True)

    # Активность (удаление — мягкое)
    is_active = Column(Boolean, default=True, nullable=False)

    # Служебные даты
    created_at = Column(DateTime(timezone=True), server_default=func.now())
    updated_at = Column(DateTime(timezone=True), onupdate=func.now())
